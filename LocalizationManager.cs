    private string _currentLanguage = "hy";

    public static event Action? LanguageChanged;

    public string CurrentLanguage
    {
        get => _currentLanguage;
        set
        {
            if (string.IsNullOrWhiteSpace(value))
                value = "hy";

            value = value.ToLowerInvariant();
            if (!StringDicts.ContainsKey(value))
            {
                string prefix = value.Split('-')[0];
                value = StringDicts.ContainsKey(prefix) ? prefix : "hy";
            }

            if (_currentLanguage != value)
            {
                _currentLanguage = value;
                OnPropertyChanged(string.Empty);
                OnPropertyChanged("Item[]");
                LanguageChanged?.Invoke();
            }
        }
    }

    public string this[string key] => Get(key);

    public static string Get(string key)
    {
        var lang = Instance._currentLanguage;
        if (StringDicts.TryGetValue(lang, out var dict) && dict.TryGetValue(key, out var val))
        {
            return val;
        }

        if (StringDicts.TryGetValue("hy", out var hyDict) && hyDict.TryGetValue(key, out var hyVal))
        {
            return hyVal;
        }

        if (StringDicts.TryGetValue("en", out var enDict) && enDict.TryGetValue(key, out var enVal))
        {
            return enVal;
        }

        return key;
    }

    public static string Format(string key, params object[] args)
    {
        string template = Get(key);
        try
        {
            return string.Format(template, args);
        }
        catch
        {
            return template;
        }
    }

    public event PropertyChangedEventHandler? PropertyChanged;
    protected void OnPropertyChanged([CallerMemberName] string? propertyName = null)
    {
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(propertyName));
    }

