using System;
using System.Collections.Generic;

namespace DesktopNotes
{
    // =========================================================
    // ՆՈԹԱՏԵՏՐ / ՏՐՑԱԿ
    // =========================================================

    public class NoteStack
    {
        // -----------------------------------------------------
        // Տրցակի կայուն, եզակի ID
        // -----------------------------------------------------

        public Guid Id { get; set; } =
            Guid.NewGuid();


        // -----------------------------------------------------
        // Տրցակի էջերը՝ ստեղծման հերթականությամբ
        // Հին → նոր
        // -----------------------------------------------------

        public List<Guid> NoteIds { get; set; } =
            new List<Guid>();


        // -----------------------------------------------------
        // Տվյալ պահին ցուցադրվող էջի ID-ն
        // -----------------------------------------------------

        public Guid? CurrentNoteId { get; set; }

        // -----------------------------------------------------
        // Տրցակի հավասարեցում՝ "TopLeft", "TopCenter", "TopRight"
        // -----------------------------------------------------

        public string Alignment { get; set; } = "TopLeft";

        // -----------------------------------------------------
        // Ուղղահայաց (զրոյական) անկյուն
        // -----------------------------------------------------

        public bool IsZeroRotation { get; set; } = false;
    }
}